  /* 兜底池轮换：按顺序取、不重复，起点随机，所以刷新后顺序不同但不会连撞同一句 */
  var genericCursor = {};
  function pickRotating(list, key) {
    if (!list) return '';
    if (typeof list === 'string') return list;
    if (!list.length) return '';
    if (!(key in genericCursor)) {
      genericCursor[key] = Math.floor(Math.random() * list.length);
    }
    var i = genericCursor[key] % list.length;
    genericCursor[key] = i + 1;
    return list[i];
  }

  function generate(text) {
    var pet = PETS[state.pet];
    var topic = null;
    for (var i = 0; i < TOPICS.length; i++) {
      if (TOPICS[i].match.test(text)) { topic = TOPICS[i]; break; }
    }

    if (topic) {
      var polite = (pet.voice && pet.voice[topic.id]) || topic.polite;
      return { polite: polite, roast: topic.roasts[pet.id], topic: topic.id, preset: true, label: topic.tag.split(' · ')[0] };
    }

    var key = '这件事';
    var runs = text.match(/[\u4e00-\u9fa5]{2,}/g) || [];
    if (runs.length) {
      var seg = runs.sort(function (a, b) { return b.length - a.length; })[0];
      seg = seg
        .replace(/^(我们|你们|他们|我|你|他|她|它)/, '')
        .replace(/^(可不可以|有没有|要不要|该不该|是不是|能不能|请问|帮我|给我|想要|的|把|给|想|要)+/g, '');
      if (seg.length >= 2) key = seg.slice(0, 6);
    }
    var line = pickRotating(pet.generic, pet.id).replace(/\{k\}/g, key);
    return {
      polite: pick(pet.politeGeneric || ['收到。先给我一点背景，我再帮你拆目标、可行性和边界。']),
      roast: line,
      topic: null,
      preset: false,
      label: key
    };
  }

